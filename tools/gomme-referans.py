"""G-43: reference data and desktop measurement for the on-device text embedder.

Uses only free tools (Hugging Face `tokenizers`, `onnxruntime`, `numpy`) on the developer's computer.
Nothing here ships in the app. Run with the model files downloaded by tools/gomme-model-indir.ps1:

    python -I -X utf8 tools/gomme-referans.py models/gomme <out-dir>

Writes:
  core/src/test/resources/embedding/reference-ids.tsv   (reference token ids, Kotlin tokenizer test)
  core/src/test/resources/embedding/pooling-fixture.txt (one model output + expected embedding)
  <out-dir>/masaustu.json                               (desktop latency + pair similarities)
"""
import ctypes
import json
import os
import statistics
import sys
import time

import numpy as np
import onnxruntime as ort
from tokenizers import Tokenizer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAIRS = os.path.join(ROOT, "app", "src", "androidTest", "assets", "gomme", "ciftler.tsv")
RES = os.path.join(ROOT, "core", "src", "test", "resources", "embedding")
MODEL = "model_qint8_avx512_vnni.onnx"
PREFIX = "query: "

# Extra inputs that exercise normalization and unknown characters (raw text, before cleanup).
TRICKY = [
    "  Annemi    ara  ",
    "Ayarları\taç\n",
    "İĞÜŞÖÇ ığüşöç I ı i İ",
    "Saat 07:30'a alarm kur",
    "Teşekkürler 🙏 çok sağ ol",
    "Ne?! Hayır... Vazgeç!",
    "ﬁlm ＡＢＣ １２３",
    "s\u0327eker",
    "𓀀𓀁 bilinmeyen",
    "e-posta: [EPOSTA_1] ve [TEL_1]",
    "Zürih'teki Œuvre café",
    "",
]


def clean(text):
    """Whitespace cleanup the Kotlin tokenizer applies before encoding (trim + collapse)."""
    return " ".join(text.split())


def esc(text):
    return text.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def read_pairs():
    pairs = []
    with open(PAIRS, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            label, a, b = line.split("\t")
            pairs.append((label, a, b))
    return pairs


def peak_rss_mb():
    if os.name != "nt":
        return None

    class Counters(ctypes.Structure):
        _fields_ = [("cb", ctypes.c_ulong), ("PageFaultCount", ctypes.c_ulong),
                    ("PeakWorkingSetSize", ctypes.c_size_t), ("WorkingSetSize", ctypes.c_size_t),
                    ("QuotaPeakPagedPoolUsage", ctypes.c_size_t), ("QuotaPagedPoolUsage", ctypes.c_size_t),
                    ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t), ("QuotaNonPagedPoolUsage", ctypes.c_size_t),
                    ("PagefileUsage", ctypes.c_size_t), ("PeakPagefileUsage", ctypes.c_size_t)]

    c = Counters()
    c.cb = ctypes.sizeof(c)
    k32 = ctypes.windll.kernel32
    k32.GetCurrentProcess.restype = ctypes.c_void_p
    k32.K32GetProcessMemoryInfo.argtypes = [ctypes.c_void_p, ctypes.POINTER(Counters), ctypes.c_ulong]
    k32.K32GetProcessMemoryInfo(k32.GetCurrentProcess(), ctypes.byref(c), c.cb)
    return round(c.PeakWorkingSetSize / 1e6, 1)


def embed(session, tok, text):
    ids = tok.encode(PREFIX + clean(text)).ids
    feed = {
        "input_ids": np.array([ids], dtype=np.int64),
        "attention_mask": np.ones((1, len(ids)), dtype=np.int64),
        "token_type_ids": np.zeros((1, len(ids)), dtype=np.int64),
    }
    hidden = session.run(["last_hidden_state"], feed)[0][0]
    vec = hidden.mean(axis=0)
    return vec / np.linalg.norm(vec), hidden, ids


def write_reference_ids(tok, pairs):
    texts = sorted({t for _, a, b in pairs for t in (a, b)})
    rows = [(PREFIX + t, PREFIX + t) for t in texts] + [(t, clean(t)) for t in TRICKY]
    os.makedirs(RES, exist_ok=True)
    with open(os.path.join(RES, "reference-ids.tsv"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/gomme-referans.py with Hugging Face tokenizers "
                f"{__import__('tokenizers').__version__} from intfloat/multilingual-e5-small tokenizer.json.\n")
        f.write("# raw input (escaped)<TAB>token ids of the cleaned input, with <s> and </s>\n")
        for raw, cleaned in rows:
            ids = tok.encode(cleaned).ids
            f.write(esc(raw) + "\t" + " ".join(map(str, ids)) + "\n")
    return len(rows)


def write_pooling_fixture(session, tok):
    vec, hidden, ids = embed(session, tok, "[KISI_1] ara")
    with open(os.path.join(RES, "pooling-fixture.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# query: [KISI_1] ara | tokens={len(ids)} dim={hidden.shape[1]}\n")
        f.write(" ".join(map(str, ids)) + "\n")
        for row in hidden:
            f.write(" ".join(f"{x:.6f}" for x in row) + "\n")
        f.write(" ".join(f"{x:.6f}" for x in vec) + "\n")


def measure(model_dir, tok, pairs):
    path = os.path.join(model_dir, MODEL)
    texts = sorted({t for _, a, b in pairs for t in (a, b)})
    result = {"model_bytes": os.path.getsize(path), "onnxruntime": ort.__version__, "threads": {}}
    for threads in (1, 2, 4):
        opts = ort.SessionOptions()
        opts.intra_op_num_threads = threads
        t0 = time.perf_counter()
        session = ort.InferenceSession(path, opts, providers=["CPUExecutionProvider"])
        load_ms = (time.perf_counter() - t0) * 1000
        t0 = time.perf_counter()
        embed(session, tok, texts[0])
        first_ms = (time.perf_counter() - t0) * 1000
        lat = []
        for _ in range(3):
            for t in texts:
                t0 = time.perf_counter()
                embed(session, tok, t)
                lat.append((time.perf_counter() - t0) * 1000)
        lat.sort()
        result["threads"][threads] = {
            "load_ms": round(load_ms), "first_query_ms": round(first_ms, 1),
            "median_ms": round(statistics.median(lat), 1), "p95_ms": round(lat[int(len(lat) * 0.95) - 1], 1),
        }
        last = session
    vecs = {t: embed(last, tok, t)[0] for t in texts}
    sims = [(label, a, b, float(np.dot(vecs[a], vecs[b]))) for label, a, b in pairs]
    result["pairs"] = [{"label": l, "a": a, "b": b, "cos": round(s, 4)} for l, a, b, s in sims]
    same = [s for l, _, _, s in sims if l == "AYNI"]
    diff = [s for l, _, _, s in sims if l == "FARKLI"]
    result["same"] = {"min": round(min(same), 4), "mean": round(statistics.mean(same), 4)}
    result["diff"] = {"max": round(max(diff), 4), "mean": round(statistics.mean(diff), 4)}

    def acc(th):
        return sum(1 for l, _, _, s in sims if (s >= th) == (l == "AYNI")) / len(sims)

    result["accuracy_at_0_80"] = round(acc(0.80), 3)
    best = max((acc(th / 1000), th / 1000) for th in range(700, 1000))
    result["best_threshold"] = {"accuracy": round(best[0], 3), "threshold": best[1]}
    result["false_accept_at_0_80"] = [f"{a} | {b} = {s:.3f}" for l, a, b, s in sims if l == "FARKLI" and s >= 0.80]
    result["false_reject_at_0_80"] = [f"{a} | {b} = {s:.3f}" for l, a, b, s in sims if l == "AYNI" and s < 0.80]
    result["peak_working_set_mb"] = peak_rss_mb()
    return result, last


def main():
    model_dir, out_dir = sys.argv[1], sys.argv[2]
    tok = Tokenizer.from_file(os.path.join(model_dir, "tokenizer.json"))
    pairs = read_pairs()
    n = write_reference_ids(tok, pairs)
    result, session = measure(model_dir, tok, pairs)
    write_pooling_fixture(session, tok)
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "masaustu.json"), "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=1)
    print(f"reference rows: {n}")
    print(json.dumps({k: v for k, v in result.items() if k != "pairs"}, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
